#!/usr/bin/env bash

set -o errexit  # Exit on error
set -o nounset  # Exit on unset variable
set -o pipefail # Exit on pipe failure

# Output extra debug logging if `DEBUG` or `TRACE` are set to `true` or `RUNNER_DEBUG` is set to `1`
# (https://docs.github.com/en/actions/reference/workflows-and-actions/variables)
if [[ "${DEBUG:-}" == "true" || "${TRACE:-}" == true || "${RUNNER_DEBUG:-}" == "1" ]]; then
	set -o xtrace # Trace the execution of the script (debug)
fi

# Regenerates the credits shown in the About panel.
#
# The hand-maintained part (the project link and the people) lives in this script. The list of
# open source libraries is generated by LicensePlist from the resolved dependency graph, so it
# cannot drift out of date the way the old hand-written list did.
#
# The result is written as Credits.html because the standard About panel picks that file up out
# of the bundle on its own, with no options dictionary and no code. That keeps the "About" button
# in the settings window and the "About CenterMouse" menu item showing exactly the same thing.

declare -r resources_dir="${PROJECT_ROOT}/CenterMouse/Resources"
declare -r credits_file="${resources_dir}/Credits.html"

# Kept out of the source tree because it is a build artifact. LicensePlist uses this directory to
# decide whether anything actually changed, which is what keeps it from hitting the network on
# every single build.
#
# When run from the Xcode build phase this has to live under TARGET_TEMP_DIR. User script
# sandboxing only grants write access to the phase's declared outputs and its own temporary
# directory, so writing anywhere else in DerivedData is denied -- including DERIVED_FILE_DIR,
# which the sandbox will not even let the script create. Outside Xcode there is no such variable,
# and DerivedData keeps it next to the rest of the build output where `mise run clean` clears it.
declare -r cache_dir="${TARGET_TEMP_DIR:-${PROJECT_ROOT}/DerivedData}/LicensePlist"
declare -r generated_file="${cache_dir}/acknowledgements.html"

function main() {
	generate_acknowledgements

	# LicensePlist skips its work entirely when the dependency graph is unchanged, in which case
	# it writes nothing. Nothing to recompose from, and Credits.html is already current.
	if [[ ! -f "${generated_file}" ]]; then
		echo "==> Credits are already up to date"
		return 0
	fi

	compose_credits
}

function generate_acknowledgements() {
	declare -a force_args=()

	# Force a run when either the generated acknowledgements or the composed credits are missing,
	# otherwise a cached "no diff" result would leave us with nothing to build from.
	if [[ ! -f "${generated_file}" || ! -f "${credits_file}" ]]; then
		force_args+=("--force")
	fi

	# LicensePlist reads mise.toml as a dependency source. That is wrong here: mise.toml lists
	# build tools, including LicensePlist itself, none of which ship inside the app. Point it at
	# an empty config instead, so only the resolved Swift packages that are actually linked into
	# CenterMouse get credited. The file has to be named mise.toml or LicensePlist rejects it.
	declare -r empty_mise_config="${cache_dir}/empty-config/mise.toml"
	mkdir -p "${empty_mise_config%/*}"
	: >"${empty_mise_config}"

	license-plist \
		--xcodeproj-path "${PROJECT_ROOT}/CenterMouse.xcodeproj" \
		--mise-path "${empty_mise_config}" \
		--output-path "${cache_dir}/plist" \
		--html-path "${generated_file}" \
		--add-sources \
		--suppress-opening-directory \
		"${force_args[@]+"${force_args[@]}"}"
}

function compose_credits() {
	declare -r temp_file="$(mktemp)"
	# shellcheck disable=SC2064 # Expand temp_file now, while it is still in scope.
	trap "rm -f '${temp_file}'" RETURN

	{
		write_preamble
		# Take LicensePlist's body but drop its own <h1> and lead-in paragraph, so the section
		# heading matches the rest of the panel.
		#
		# The sed repairs malformed markup from --add-sources, which emits an anchor whose opening
		# tag is never closed: <a href="URL"<h2>Name</h2></a>. Rewritten into a heading that links
		# to the library's source, which is what that flag is trying to produce.
		awk '/<h2>/,/<\/body>/ { if ($0 !~ /<\/body>/) print }' "${generated_file}" |
			sed -E 's|<a href="([^"]+)"<h2>([^<]+)</h2></a>|<h2><a href="\1">\2</a></h2>|g'
		write_postamble
	} >"${temp_file}"

	# Only replace the real file when something actually changed. Rewriting it every build would
	# re-trigger the resource copy and dirty the working tree on every single build.
	if [[ -f "${credits_file}" ]] && cmp --silent "${temp_file}" "${credits_file}"; then
		echo "==> Credits unchanged"
		return 0
	fi

	mv "${temp_file}" "${credits_file}"
	# mktemp creates 0600, which is not what a checked-in resource should be.
	chmod 644 "${credits_file}"
	trap - RETURN
	echo "==> Wrote ${credits_file}"
}

function write_preamble() {
	# Helvetica Neue on purpose. This HTML is parsed by the NSAttributedString importer, and font
	# families it cannot resolve fall back to Times New Roman silently.
	cat <<-'HTML'
		<!DOCTYPE html>
		<html lang="en">
		<head>
		<meta charset="utf-8">
		<title>Credits</title>
		<style>
		body { font-family: "Helvetica Neue", Helvetica, sans-serif; font-size: 13px; }
		h2 { font-size: 15px; font-weight: 500; margin: 12px 0 4px 0; }
		h3 { font-size: 13px; font-style: italic; font-weight: bold; margin: 8px 0 0 0; }
		p { margin: 2px 0; }
		pre { font-family: "Helvetica Neue", Helvetica, sans-serif; font-size: 11px; white-space: pre-wrap; margin: 2px 0 8px 0; }
		</style>
		</head>
		<body>
		<p>More info: <a href="https://hisaac.net/CenterMouse">hisaac.net/CenterMouse</a></p>

		<h2>Credits</h2>
		<h3>Programming</h3>
		<p>Isaac Halvorson</p>
		<h3>Initial Idea and QA Testing</h3>
		<p>Eli Mellen</p>

		<h2>Open Source Libraries</h2>
	HTML
}

function write_postamble() {
	cat <<-'HTML'
		</body>
		</html>
	HTML
}

trap handle_exit EXIT
function handle_exit() {
	declare -ri exit_code="$?"
	if [[ "${exit_code}" -ne 0 ]]; then
		declare -r script_name="${0##*/}"
		echo -e "\n==> ${script_name} exited with code ${exit_code}"
	fi
}

main "$@"
